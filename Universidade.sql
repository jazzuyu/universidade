CREATE PROCEDURE sp_CadastraNotas
(
    @MATRICULA INT,
    @CURSO CHAR(3),
    @MATERIA CHAR(3),
    @PERLETIVO CHAR(4),
    @NOTA FLOAT,
    @FALTA INT,
    @BIMESTRE INT
)
AS
BEGIN

    IF @BIMESTRE = 1
    BEGIN
        UPDATE MATRICULA
        SET N1 = @NOTA,
            F1 = @FALTA,
            TOTALPONTOS = @NOTA,
            TOTALFALTAS = @FALTA,
            MEDIA = @NOTA
        WHERE MATRICULA = @MATRICULA
            AND CURSO = @CURSO
            AND MATERIA = @MATERIA
            AND PERLETIVO = @PERLETIVO;
    END

    ELSE

    IF @BIMESTRE = 2
    BEGIN
        UPDATE MATRICULA
        SET N2 = @NOTA,
            F2 = @FALTA,
            TOTALPONTOS = @NOTA + N1,
            TOTALFALTAS = @FALTA + F1,
            MEDIA = (@NOTA + N1) / 2
        WHERE MATRICULA = @MATRICULA
            AND CURSO = @CURSO
            AND MATERIA = @MATERIA
            AND PERLETIVO = @PERLETIVO;
    END

    ELSE

    IF @BIMESTRE = 3
    BEGIN
        UPDATE MATRICULA
        SET N3 = @NOTA,
            F3 = @FALTA,
            TOTALPONTOS = @NOTA + N1 + N2,
            TOTALFALTAS = @FALTA + F1 + F2,
            MEDIA = (@NOTA + N1 + N2) / 3
        WHERE MATRICULA = @MATRICULA
            AND CURSO = @CURSO
            AND MATERIA = @MATERIA
            AND PERLETIVO = @PERLETIVO;
    END

    ELSE

    IF @BIMESTRE = 4
    BEGIN

        DECLARE @RESULTADO VARCHAR(20),
                @FREQUENCIA FLOAT,
                @MEDIA FLOAT,
                @FALTAS INT,
                @CARGAHORA INT

        SET @CARGAHORA = (SELECT CARGAHORARIA FROM MATERIAS
                          WHERE SIGLA = @MATERIA
                            AND CURSO = @CURSO)

        UPDATE MATRICULA
        SET N4 = @NOTA,
            F4 = @FALTA,
            TOTALPONTOS = @NOTA + N1 + N2 + N3,
            TOTALFALTAS = @FALTA + F1 + F2 + F3,
            MEDIA = (@NOTA + N1 + N2 + N3) / 4
        WHERE MATRICULA = @MATRICULA
            AND CURSO = @CURSO
            AND MATERIA = @MATERIA
            AND PERLETIVO = @PERLETIVO;

        SELECT @MEDIA = MEDIA, @FALTAS = TOTALFALTAS
        FROM MATRICULA
        WHERE MATRICULA = @MATRICULA
            AND CURSO = @CURSO
            AND MATERIA = @MATERIA
            AND PERLETIVO = @PERLETIVO;

        SET @FREQUENCIA = (@CARGAHORA - @FALTAS) * 100.0 / @CARGAHORA

        IF @FREQUENCIA < 75
            SET @RESULTADO = 'REPROVADO POR FALTA'
        ELSE IF @MEDIA >= 7
            SET @RESULTADO = 'APROVADO'
        ELSE IF @MEDIA >= 4
            SET @RESULTADO = 'EXAME'
        ELSE
            SET @RESULTADO = 'REPROVADO'

        UPDATE MATRICULA
        SET PERCFREQ = @FREQUENCIA,
            RESULTADO = @RESULTADO
        WHERE MATRICULA = @MATRICULA
            AND CURSO = @CURSO
            AND MATERIA = @MATERIA
            AND PERLETIVO = @PERLETIVO;

    END

    SELECT * FROM MATRICULA WHERE MATRICULA = @MATRICULA
END
GO


-- Procedure do exame
CREATE PROCEDURE sp_LancaExame
(
    @MATRICULA INT,
    @CURSO CHAR(3),
    @MATERIA CHAR(3),
    @PERLETIVO CHAR(4),
    @NOTAEXAME FLOAT
)
AS
BEGIN

    UPDATE MATRICULA
    SET NOTAEXAME = @NOTAEXAME,
        MEDIAFINAL = (MEDIA + @NOTAEXAME) / 2,
        RESULTADO = CASE WHEN (MEDIA + @NOTAEXAME) / 2 >= 5
                         THEN 'APROVADO'
                         ELSE 'REPROVADO'
                    END
    WHERE MATRICULA = @MATRICULA
        AND CURSO = @CURSO
        AND MATERIA = @MATERIA
        AND PERLETIVO = @PERLETIVO
        AND RESULTADO = 'EXAME';

    SELECT * FROM MATRICULA WHERE MATRICULA = @MATRICULA
END
GO


